# Самотесты loft — 10-link-check. Подключается из test/run.sh; переменные REPO/SK/HK/TMP
# и функции ok/bad/has/hasnt/section приходят оттуда.

LCP="$SK/link-check/scripts/link_check.py"

# ── link_check: битые, фенсы, \|-алиасы, картинки ───────────────────────────
section "link_check — резолюция и фенсы"
L="$TMP/lc"; mkdir -p "$L/spec"
cat > "$L/spec/a.md" <<'EOF'
Живая: [[b]] и с алиасом в таблице [[b\|текст]].
Битая: [[нет-такой]]. Картинка битая: ![x](assets/nope.png)
```
[[в-фенсе-не-считается]]
```
EOF
echo "# b" > "$L/spec/b.md"
out="$(cd "$L" && python3 "$LCP" spec 2>&1)"; rc=$?
has "ссылок проверено: 4" "$out" "экранированный алиас посчитан как ссылка"
has "битых: 2" "$out" "ровно две битые (wikilink + картинка)"
hasnt "в-фенсе" "$out" "код-фенс пропускается"
hasnt "[[b\\" "$out" "экранированный алиас резолвится"
[ "$rc" -eq 1 ] && ok || bad "exit 1 при битых (got $rc)"
out="$(cd "$L" && python3 "$LCP" spec nope-dir 2>&1)"
has "не существует и пропущен" "$out" "предупреждение о несуществующем каталоге"
out="$(cd "$L" && python3 "$LCP" spec nope-dir 2>/dev/null)"
hasnt "warning" "$out" "предупреждения идут в stderr, не в отчёт"

# ── link_check: «]» внутри алиаса ──────────────────────────────────────────
# В корпусе живут алиасы вида "[TO BE] Валидация": запрет на "]" в алиасе делал
# такую строку не ссылкой вовсе, а её цель — сиротой.
section "link_check — скобки в алиасе"
L6="$TMP/lc6"; mkdir -p "$L6/spec"
: > "$L6/spec/цель.md"; printf '## раздел\n' > "$L6/spec/b.md"   # цель якоря
cat > "$L6/spec/README.md" <<'EOF'
Обычная: [[b]].
Алиас со скобками: [[цель|[TO BE] Валидация]].
Экранированный разделитель: | [[цель\|[x] алиас]] |
Якорь и скобки: [[b#раздел|[draft] Заголовок]].
Битая со скобками: [[нет-такой|[TBD] Нет]].
Две в строке: [[b|алиас]] и [[цель|другой]].
EOF
out="$(cd "$L6" && python3 "$LCP" spec 2>&1)"; rc=$?
has "ссылок проверено: 7 · битых: 1" "$out" "«]» в алиасе не отменяет ссылку"
has "[[нет-такой]]" "$out" "битая ссылка с алиасом-скобками названа по цели"
has "сирот: 0" "$out" "цель алиаса со скобками не сирота"
hasnt "ORPHAN  spec/цель.md" "$out" "[[цель|[TO BE] ...]] засчитана как входящая"
hasnt "ORPHAN  spec/b.md" "$out" "[[b#раздел|[draft] ...]] засчитана как входящая"
[ "$rc" -eq 1 ] && ok || bad "exit 1 при битой ссылке с алиасом-скобками (got $rc)"

# ── link_check: инлайн-код, комментарии, отступной код, длинные фенсы ───────
section "link_check — код и комментарии не считаются"
L2="$TMP/lc2"; mkdir -p "$L2/spec"
: > "$L2/spec/t.md"
cat > "$L2/spec/code.md" <<'EOF'
Живая: [[t]].
Инлайн: `[[в-инлайне]]` и `[x](в-инлайне.md)`.
<!-- [[в-комментарии]] -->
<!-- многострочный
[[в-комментарии-2]]
--> и после комментария [[t]].

````
```
[[в-4-фенсе]]
```
````
После 4-фенса: [[t]].

    [[в-отступном-коде]]

- пункт

    продолжение пункта [[t]]
EOF
out="$(cd "$L2" && python3 "$LCP" spec --no-orphans 2>&1)"; rc=$?
has "ссылок проверено: 4 · битых: 0" "$out" "считаются только ссылки вне кода"
hasnt "в-инлайне" "$out" "инлайн-код пропускается"
hasnt "в-комментарии" "$out" "HTML-комментарий пропускается (в т.ч. многострочный)"
hasnt "в-4-фенсе" "$out" "фенс из 4 бэктиков не рвётся вложенным тройным"
hasnt "в-отступном-коде" "$out" "отступной код пропускается"
[ "$rc" -eq 0 ] && ok || bad "exit 0 без битых (got $rc)"

# ── link_check: путь в цели, регистр, NFC/NFD ──────────────────────────────
section "link_check — пути, регистр, юникод"
L3="$TMP/lc3"; mkdir -p "$L3/spec/d1" "$L3/spec/d2"
NFC_J=$(printf '\xd0\xb9')            # «й» одной кодовой точкой
NFD_J=$(printf '\xd0\xb8\xcc\x86')    # «и» + U+0306
NFC_YO=$(printf '\xd1\x91')           # «ё» одной кодовой точкой
NFD_YO=$(printf '\xd0\xb5\xcc\x88')   # «е» + U+0308
: > "$L3/spec/Case.md"
: > "$L3/spec/$NFD_J.md"
: > "$L3/spec/$NFC_YO.md"
: > "$L3/spec/d1/dup.md"
: > "$L3/spec/d2/dup.md"
{ printf 'Путь: [[d2/dup]].\n'
  printf 'Голый дубль: [[dup]].\n'
  printf 'Регистр: [[case]].\n'
  printf 'NFD-файл, NFC-ссылка: [[%s]].\n' "$NFC_J"
  printf 'NFC-файл, NFD-ссылка: [[%s]].\n' "$NFD_YO"
  printf 'Мимо: [[d3/dup]].\n'; } > "$L3/spec/main.md"
out="$(cd "$L3" && python3 "$LCP" spec 2>&1)"
has "ссылок проверено: 6 · битых: 1" "$out" "разрешаются все цели, кроме несуществующего пути"
has "[[d3/dup]]" "$out" "цель с путём не откатывается на basename"
hasnt "spec/main.md:3" "$out" "резолв без учёта регистра"
hasnt "spec/main.md:4" "$out" "NFD-имя файла и NFC-ссылка — одно и то же"
hasnt "spec/main.md:5" "$out" "NFC-имя файла и NFD-ссылка — одно и то же"
has "сирот: 1" "$out" "цель по пути засчитана как входящая ссылка"
hasnt "ORPHAN  spec/d2/dup.md" "$out" "[[d2/dup]] ведёт именно в d2"
has "неоднозначно: 2 кандидатов" "$out" "дубль basename — предупреждение"
has "выбран spec/d1/dup.md" "$out" "дубль basename — лексически первый кандидат"

# ── link_check: формы относительных ссылок ─────────────────────────────────
section "link_check — пробелы, скобки, якоря в путях"
L4="$TMP/lc4"; mkdir -p "$L4/spec"
: > "$L4/spec/с пробелом.md"; : > "$L4/spec/файл(1).md"
printf '## раздел\n' > "$L4/spec/b.md"                          # цель якоря
cat > "$L4/spec/links.md" <<'EOF'
Угловые: [t](<с пробелом.md>)
Percent: [t](с%20пробелом.md)
Голый пробел: [t](с пробелом.md)
Скобка в имени: [t](файл(1).md)
С подсказкой: [t](b.md "подсказка")
Внешняя: [t](https://example.com/a-b)
Якорь: [t](b.md#раздел)
Битая: [t](<нет такого.md>)
EOF
out="$(cd "$L4" && python3 "$LCP" spec --no-orphans 2>&1)"
has "ссылок проверено: 7 · битых: 1" "$out" "пробелы, %20, скобки и якоря разрешаются"
has "нет такого.md" "$out" "битая ссылка с пробелом видна в отчёте"
hasnt "example.com" "$out" "внешние ссылки не проверяются"
hasnt "якорей не найдено" "$out" "сводка без ненайденных якорей прежняя"
hasnt "WARN" "$out" "относительная ссылка со скобками в имени файла не даёт предупреждения"

# ── link_check: сироты и разбор флагов ─────────────────────────────────────
section "link_check — сироты и флаги"
L5="$TMP/lc5"; mkdir -p "$L5/spec"
echo "хаб: [[живая]]" > "$L5/spec/README.md"
: > "$L5/spec/живая.md"
: > "$L5/spec/сирота.md"
for f in _служебная.md home.md MEMORY.md index.md; do : > "$L5/spec/$f"; done
out="$(cd "$L5" && python3 "$LCP" spec 2>&1)"; rc=$?
has "сирот: 1" "$out" "сирота ровно одна"
has "ORPHAN  spec/сирота.md" "$out" "страница без входящих — сирота"
hasnt "ORPHAN  spec/home.md" "$out" "служебные исключаются без учёта регистра"
hasnt "ORPHAN  spec/index.md" "$out" "index.md сиротой не считается"
hasnt "ORPHAN  spec/_служебная.md" "$out" "_-префикс сиротой не считается"
[ "$rc" -eq 0 ] && ok || bad "exit 0 без битых (got $rc)"
out="$(cd "$L5" && python3 "$LCP" spec --no-orphans 2>&1)"
has "сирот: 0" "$out" "--no-orphans выключает поиск сирот"
hasnt "ORPHAN" "$out" "--no-orphans не печатает сирот"
(cd "$L5" && python3 "$LCP" spec --no-orphan) >/dev/null 2>&1
[ "$?" -eq 2 ] && ok || bad "неизвестный флаг → exit 2"
(cd "$L5" && python3 "$LCP") >/dev/null 2>&1
[ "$?" -eq 2 ] && ok || bad "без каталогов → exit 2"

# ── link_check: reference-ссылки ───────────────────────────────────────────
# CommonMark link reference definitions: «[ref]: путь "title"» в конце файла,
# использование — [текст][ref] или [ref]. Проверяются цели определений;
# сокращённая форма от обычного текста в скобках неотличима, и неопределённый
# ref — повод для предупреждения, а не для BROKEN.
section "link_check — reference-определения"
L7="$TMP/lc7"; mkdir -p "$L7/spec"
: > "$L7/spec/цель.md"; : > "$L7/spec/с пробелом.md"
cat > "$L7/spec/ref.md" <<'EOF'
Полная форма: [текст][есть], сокращённая: [есть].
Коллапс: [есть][].
Неопределённая: [текст][нет-такого].
Текст в скобках: [TO BE] — не ссылка и не предупреждение.
Абзац продолжается:
[в-абзаце]: нет-файла.md

```
[в-фенсе]: цель.md
```

[есть]: цель.md "подсказка"
[пробел]: <с пробелом.md>
[битая]: нет-такого-файла.md
[внешняя]: https://example.com/x
[термин]: описание из нескольких слов
EOF
out="$(cd "$L7" && python3 "$LCP" spec --no-orphans 2>&1)"; rc=$?
has "ссылок проверено: 3 · битых: 1" "$out" "цели определений проверены, внешняя пропущена"
has "BROKEN  spec/ref.md:14 → нет-такого-файла.md" "$out" "битое определение названо файлом и строкой"
hasnt "в-фенсе" "$out" "определение внутри фенса не считается"
hasnt "нет-файла.md" "$out" "определение не прерывает абзац (CommonMark)"
hasnt "описание" "$out" "хвост без title — не определение, а текст"
has "нет определения для ссылки [нет-такого]" "$out" "неопределённый ref — предупреждение"
hasnt "BROKEN  spec/ref.md:3" "$out" "неопределённый ref не битая ссылка"
hasnt "[TO BE]" "$out" "текст в скобках не выдаётся за ссылку"
[ "$rc" -eq 1 ] && ok || bad "exit 1 при битом определении (got $rc)"
out="$(cd "$L7" && python3 "$LCP" spec --no-orphans 2>/dev/null)"
hasnt "нет определения" "$out" "предупреждение о ref идёт в stderr"
out="$(cd "$L7" && python3 "$LCP" spec 2>&1)"
hasnt "ORPHAN  spec/цель.md" "$out" "цель определения засчитана как входящая ссылка"
hasnt "ORPHAN  spec/с пробелом.md" "$out" "<путь с пробелом> в определении разрешается"

# ── link_check: фрагменты #якорь ───────────────────────────────────────────
# Ссылка ведёт не на страницу, а в раздел: [[стр#якорь]], [[#якорь]] (цель —
# текущая страница) и [t](файл.md#якорь). Цель фрагмента — заголовок,
# block-id «^id» или <a name>/id= в сыром HTML; конвертер пишет все три.
section "link_check — фрагменты и якоря"
L8="$TMP/lc8"; mkdir -p "$L8/spec"
cat > "$L8/spec/цель.md" <<'EOF'
# Цель

## **Тариф** и `код` ##

Пункт с block-id. ^blk-1

<a name="ЯкорьHTML"></a>Раздел под якорем.

<a name="раздел 1"></a>Пробел в имени якоря.

| Ключ | Смысл |
|----|----|
| <span id="в-таблице"></span>k1 | v1 |

## Получение_pan

```
## В-фенсе-не-якорь
```
EOF
cat > "$L8/spec/src.md" <<'EOF'
Заголовок с разметкой и регистром: [[цель#тариф И КОД]].
Block-id: [[цель#blk-1]] и ссылка на блок [[цель#^blk-1]].
Якорь <a name>: [[цель#якорьhtml]], id= в таблице: [[цель#в-таблице]].
Подчёркивание не курсив: [[цель#Получение_pan]].
Md-ссылка с фрагментом: [t](цель.md#blk-1), с %XX: [t](цель.md#раздел%201).
Свой якорь: [[#Свой раздел]] и [[#свой-блок|текст]].
Нет якоря: [[цель#нет-такого]].
Md-ссылка мимо: [t](цель.md#мимо).
Фенс не даёт якоря: [[цель#В-фенсе-не-якорь]].

## Свой раздел

<a name="свой-блок"></a>
EOF
out="$(cd "$L8" && python3 "$LCP" spec 2>&1)"; rc=$?
has "ссылок проверено: 13 · битых: 3 · сирот: 1 · якорей не найдено: 3" "$out" \
  "фрагменты посчитаны, ненайденные якоря — отдельной цифрой в сводке"
hasnt "spec/src.md:1" "$out" "заголовок с разметкой и другим регистром — найден"
hasnt "spec/src.md:2" "$out" "block-id ^id — найден и как #id, и как #^id"
hasnt "spec/src.md:3" "$out" "<a name> и id= в сыром HTML — найдены"
hasnt "spec/src.md:4" "$out" "подчёркивание в заголовке не курсив"
hasnt "spec/src.md:5" "$out" "md-ссылка с фрагментом и %XX — найдена"
hasnt "spec/src.md:6" "$out" "[[#якорь]] на свою страницу — найден"
has "BROKEN  spec/src.md:7 → [[цель#нет-такого]]  (якорь не найден)" "$out" \
  "ненайденный якорь — битая ссылка с пометкой"
has "BROKEN  spec/src.md:8 → цель.md#мимо  (якорь не найден)" "$out" \
  "ненайденный якорь md-ссылки — битая с пометкой"
has "BROKEN  spec/src.md:9 → [[цель#В-фенсе-не-якорь]]  (якорь не найден)" "$out" \
  "заголовок внутри фенса якоря не даёт"
has "ORPHAN  spec/src.md" "$out" "[[#якорь]] не засчитывается себе как входящая"
hasnt "ORPHAN  spec/цель.md" "$out" "страница с ненайденным якорем не сирота"
[ "$rc" -eq 1 ] && ok || bad "exit 1 при ненайденном якоре (got $rc)"

# ── link_check: предупреждение о скобках и пробеле в url ───────────────────
# Внешний url со схемой (http, mailto и прочие), не взятый в <…>: буквальные
# «(»/«)» или пробел рвут ссылку в Confluence и наивных md-рендерах, хоть
# здесь она резолвится верно (парные скобки посчитаны). Это WARN, не BROKEN.
section "link_check — предупреждение о скобках и пробеле в url"
L9="$TMP/lc9"; mkdir -p "$L9/spec"
cat > "$L9/spec/warn.md" <<'EOF'
Скобки: [t](https://example.org/pages/Подтверждение+платежа+(списание))
В угловых: [t](<https://example.org/скобки+(ок)>)
Percent: [t](https://example.org/percent-%28ok%29)
Пробел: [t](https://example.org/path with space)
EOF
out="$(cd "$L9" && python3 "$LCP" spec --no-orphans 2>&1)"; rc=$?
has "WARN spec/warn.md:1 → https://example.org/pages/Подтверждение+платежа+(списание)  (скобки в url без экранирования)" \
  "$out" "непроэкранированные скобки в url — предупреждение"
hasnt "spec/warn.md:2" "$out" "url в <…> предупреждения не даёт"
hasnt "spec/warn.md:3" "$out" "%28/%29 предупреждения не даёт"
has "WARN spec/warn.md:4 → https://example.org/path with space  (пробел в url)" \
  "$out" "пробел в url — предупреждение"
has "предупреждений: 2" "$out" "счётчик предупреждений в сводке"
[ "$rc" -eq 0 ] && ok || bad "предупреждения не меняют exit code (got $rc)"
out="$(cd "$L9" && python3 "$LCP" spec --no-orphans 2>/dev/null)"
hasnt "WARN" "$out" "предупреждения о скобках/пробеле идут в stderr, не в отчёт"
